// One-shot generator for the achievements.description backfill migration.
//
// Combines TWO sources:
//   1. supabase/seed/achievements.sql — the 200 originally-curated logros
//      that already have descriptions baked in.
//   2. scripts/descriptions-data.mjs — hand-curated descriptions (and
//      occasional LATAM-fix title rewrites) for the v2/v3 catalog
//      entries that don't have descriptions in any seed file.
//
// Output: supabase/migrations/20260506000019_restore_achievement_description.sql
//   - ADD COLUMN IF NOT EXISTS description text
//   - One UPDATE ... FROM (values ...) per source, atomic via two
//     statements
//   - Optional UPDATE for any title rewrites
//
// Pattern: UPDATE-only via VALUES join. Never INSERT — we must preserve
// existing UUIDs of every row (foreign keys in unlocks/stories/passes
// depend on them).
//
// Usage:
//   node scripts/build-restore-description-migration.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { NEW_DESCRIPTIONS } from "./descriptions-data.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..");
const SEED_PATH = join(REPO_ROOT, "supabase", "seed", "achievements.sql");
const MIGRATION_PATH = join(
  REPO_ROOT,
  "supabase",
  "migrations",
  "20260506000019_restore_achievement_description.sql",
);

// Match each tuple in the seed (the original 200 with descriptions):
//   ('slug', 'title', 'emoji', 'description', 'category', 'status')
const ROW_RE =
  /\(\s*'([^']+)'\s*,\s*'((?:[^'\\]|\\.|'')*)'\s*,\s*'([^']+)'\s*,\s*'((?:[^'\\]|\\.|'')*)'\s*,\s*'(\w+)'\s*,\s*'(\w+)'\s*\)/g;

function unescapeBackslashes(s) {
  // Seed uses \' for apostrophes (legacy MySQL-style). Convert to a raw
  // apostrophe; quotePg handles the final PG escaping. Doing PG escape
  // here AND in quotePg double-escapes (McDonald\'s → McDonald''''s).
  return s.replace(/\\'/g, "'");
}

function quotePg(s) {
  return `'${s.replace(/'/g, "''")}'`;
}

function parseOriginalSeed() {
  const seed = readFileSync(SEED_PATH, "utf8");
  const rows = [];
  let m;
  while ((m = ROW_RE.exec(seed)) !== null) {
    rows.push({
      slug: m[1],
      title: unescapeBackslashes(m[2]),
      emoji: m[3],
      description: unescapeBackslashes(m[4]),
      category: m[5],
      status: m[6],
    });
  }
  if (rows.length === 0) {
    throw new Error("Parsed 0 rows from original seed — regex broke");
  }
  return rows;
}

function main() {
  // 1. Originals from achievements.sql (200 entries with descriptions
  //    baked into the seed).
  const originals = parseOriginalSeed();
  const originalSlugs = new Set(originals.map((r) => r.slug));

  // 2. Hand-curated additions from descriptions-data.mjs (v2/v3 catalog
  //    entries that don't have descriptions in any seed). Skip any that
  //    overlap with originals — original seed wins.
  const additions = Object.entries(NEW_DESCRIPTIONS)
    .filter(([slug]) => !originalSlugs.has(slug))
    .map(([slug, { description, newTitle }]) => ({
      slug,
      description,
      newTitle: newTitle ?? null,
    }));

  // Combined description rows
  const allDescriptions = [
    ...originals.map((r) => ({ slug: r.slug, description: r.description })),
    ...additions.map((r) => ({ slug: r.slug, description: r.description })),
  ];

  // Title-rewrite rows (only the additions with newTitle set)
  const titleRewrites = additions.filter((a) => a.newTitle !== null);

  const header = `-- =================================================================
-- Restore the achievements.description column + backfill descriptions
-- across the catalog.
--
-- Migration _014 dropped this column. We're un-dropping it because the
-- short witty description below the title turned out to be a real
-- product asset visually (decision reversed in the rebrand-to-Unlocky
-- iteration).
--
-- Sources:
--   - supabase/seed/achievements.sql: 200 originally-curated logros
--     with descriptions baked into the seed
--   - scripts/descriptions-data.mjs: hand-curated descriptions for
--     v2/v3 catalog entries that don't have one in any seed file
--
-- Pattern: UPDATE-only via VALUES join. NO INSERT ON CONFLICT because
-- we must preserve every achievement row's UUID — an INSERT for a
-- missing slug would create a new row with a new UUID, breaking
-- foreign-key links in unlocks/stories/passes. If a slug from this
-- migration doesn't exist in the DB (drift), the WHERE silently skips
-- it.
--
-- A few entries also have title rewrites (humanización España on
-- LATAM-flavored phrasings); those go in a separate UPDATE statement
-- so a description-only entry doesn't accidentally null out a title.
--
-- Generated by scripts/build-restore-description-migration.mjs.
-- Re-running the script regenerates this file deterministically.
-- Idempotent: re-applying the migration is safe.
-- =================================================================

alter table achievements add column if not exists description text;

`;

  const descSql = `-- ${allDescriptions.length} description backfills (originals + hand-curated)
update achievements as a
set description = v.description
from (values
${allDescriptions.map((r) => `  (${quotePg(r.slug)}, ${quotePg(r.description)})`).join(",\n")}
) as v(slug, description)
where a.slug = v.slug;
`;

  let titleSql = "";
  if (titleRewrites.length > 0) {
    titleSql = `
-- ${titleRewrites.length} title rewrites (humanización España on LATAM phrasings)
update achievements as a
set title = v.title
from (values
${titleRewrites.map((r) => `  (${quotePg(r.slug)}, ${quotePg(r.newTitle)})`).join(",\n")}
) as v(slug, title)
where a.slug = v.slug;
`;
  }

  writeFileSync(MIGRATION_PATH, header + descSql + titleSql, "utf8");

  console.log(`Originals: ${originals.length}`);
  console.log(`Additions (v2/v3 hand-curated): ${additions.length}`);
  console.log(`Total description UPDATEs: ${allDescriptions.length}`);
  console.log(`Title rewrites: ${titleRewrites.length}`);
  console.log(`→ ${MIGRATION_PATH}`);
}

main();
